// Package docgen generates the user command reference from CLI help.
package docgen

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/fluid-movement/prep/internal/cli"
)

// Commands renders help without the build-dependent version banner.
func Commands() ([]byte, error) {
	var out, stderr bytes.Buffer
	if code := cli.Main([]string{"help", "--root", "."}, strings.NewReader(""), &out, &stderr); code != 0 {
		return nil, fmt.Errorf("prep help: %s", stderr.String())
	}
	_, help, ok := strings.Cut(out.String(), "\n\n")
	if !ok {
		return nil, fmt.Errorf("prep help: missing banner")
	}
	return []byte("# Commands\n\n[Documentation](../README.md#documentation)\n\n" +
		"<!-- Generated by just docs-commands; do not edit. -->\n\n" +
		"```text\n" + help + "```\n"), nil
}
